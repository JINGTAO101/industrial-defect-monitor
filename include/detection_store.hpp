#pragma once

#include <cstdint>
#include <memory>
#include <string>
#include <vector>

#include "image_source.hpp"
#include "postprocess.hpp"

namespace edge_ai {

struct DefectRecord {
    int class_id = -1;
    std::string class_name;
    float confidence = 0.0f;
    float x1 = 0.0f;
    float y1 = 0.0f;
    float x2 = 0.0f;
    float y2 = 0.0f;
};

struct DetectionEvent {
    std::string event_uid;  // generated by the store when empty
    std::int64_t occurred_at_ms = 0;
    std::string source;
    std::string product_id;
    bool is_ng = false;
    std::size_t defect_count = 0;
    std::string model_identifier;  // sha256 of the model
    std::string model_path;
    std::string image_path;  // may be empty until FR-013
    float confidence_threshold = 0.0f;
    std::vector<DefectRecord> defects;
};

struct EventQuery {
    enum class StatusFilter { Any, Ok, Ng };

    bool has_from = false;
    std::int64_t from_ms = 0;
    bool has_to = false;
    std::int64_t to_ms = 0;
    StatusFilter status = StatusFilter::Any;
    bool has_product_id = false;
    std::string product_id;
};

// SQLite-backed detection event store. One event and all of its defect rows
// are committed in a single transaction; any failure rolls the whole event
// back. Open with create=false for the independent query entry.
class DetectionStore {
public:
    DetectionStore();
    ~DetectionStore();

    DetectionStore(const DetectionStore&) = delete;
    DetectionStore& operator=(const DetectionStore&) = delete;

    bool open(const std::string& path, bool create, std::string& error);
    void close() noexcept;
    bool isOpen() const;

    bool insertEvent(DetectionEvent& event, std::string& error);

    bool query(const EventQuery& query,
               std::vector<DetectionEvent>& events,
               std::string& error);

private:
    struct Impl;
    std::unique_ptr<Impl> impl_;
};

// Helpers shared by the CLI, tests and query output.
std::string generateEventUid();
std::int64_t toEpochMillis(FrameTimestamp timestamp);
std::string formatEpochMillisIso(std::int64_t epoch_ms);

// Accepts either an integer epoch in milliseconds or an ISO-8601 UTC value
// such as 2026-11-20T10:00:00Z (fractional .mmm allowed). Returns false and
// sets error for anything else.
bool parseTimestampToEpochMillis(const std::string& text,
                                 std::int64_t& epoch_ms,
                                 std::string& error);

}  // namespace edge_ai
